package com.atlasmountains.core;

/**
 * Every size, angle, spacing and strength used by the generator, in one place.
 *
 * <h2>Rules for this class</h2>
 * <ul>
 *   <li>Units are blocks unless a comment says otherwise. Slopes are given as tangents
 *       (rise over run): 1.0 is 45 degrees, 0.58 is 30 degrees, 1.73 is 60 degrees.</li>
 *   <li>Tuning is done by changing these values, never by rewriting generator code. Every value
 *       here was tuned in game against Sammi's screenshots, so a change is a design change: the
 *       mountain size, height and proportions are fixed unless he asks for them to change.</li>
 *   <li>Several heights are repeated in {@code tools/build_datapack.py}, because the datapack is
 *       generated by a Python script that cannot read this class. {@code SettingsSyncTest} fails the
 *       build if the two disagree, so change both together.</li>
 *   <li>A fresh instance always holds the shipped values. The fields are public and mutable so
 *       the diagnostic tools and tests can try alternatives without a build.</li>
 * </ul>
 *
 * <h2>How the pieces fit together</h2>
 * The terrain is built in this order, and the sections below follow it:
 * <ol>
 *   <li>{@link FieldLayout} decides where ridges run (the field layout settings).</li>
 *   <li>{@link HeightmapGenerator} turns the distance to a ridge into a height: a crest that
 *       strings summits along the ridge ({@link CrestProfile}, crest settings), and a cross
 *       section from the crest down to the valley floor ({@link CrossProfile}, cross profile
 *       settings). Detail noise roughens the upper faces, and valley floors get lakes.</li>
 *   <li>{@link RegionPipeline} samples that height on a grid one region at a time and erodes it
 *       (thermal, then hydraulic, then thermal again), which carves the gullies.</li>
 *   <li>{@link RegionCache} serves the eroded height to Minecraft at block resolution, and
 *       {@link MountainMask} fades it out where vanilla terrain takes over: outside vanilla's
 *       mountain footprint and near coasts.</li>
 * </ol>
 */
public final class MountainSettings {

    // ---- Region grid -------------------------------------------------------------
    /**
     * Side of one region in blocks. Erosion runs on a whole region at once, so this is the unit of
     * work and of the on-disk cache: one region is (2048 / sampleSpacing)^2 = 262 144 samples plus
     * the overlap. Larger regions mean fewer seams but a longer wait for the first one.
     */
    public int regionSizeBlocks = 2048;

    // ---- Field layout (see FieldLayout) --------------------------------------------
    /**
     * Voronoi cell size. The layout scatters one site per square of this size and the ridges are the
     * edges between neighbouring sites' cells, so neighbouring ridges sit about this far apart and
     * each enclosed cell is about this wide. Cells wider than two flanks (2 x halfWidth()) leave a
     * small flat valley floor in the middle; narrower ones put two ranges back to back.
     */
    public double fieldCellSize = 420;
    /**
     * How far each site may wander from the centre of its square, as a fraction of the cell
     * (0 = a perfect square grid, so every cell is a square; 1 = anywhere in the square). 0.9 keeps
     * the network irregular without letting two sites land on top of each other.
     */
    public double fieldJitter = 0.9;
    /** Half-length of the spine of a mountain cell with no mountain neighbour, in cells. */
    public double loneSpineHalfLength = 0.4;
    /** A spine's free end drops by this share of its relief over spineTaperLength blocks, so ranges tail off instead of ending at full height. */
    public double spineEndDrop = 0.45;
    public double spineTaperLength = 160;
    /**
     * Domain warp of the diagram, so the ridges curve instead of running as straight Voronoi edges:
     * amplitude of the main octave in blocks (a second octave at 2.3 times the frequency adds a
     * quarter of this), and its wavelength. The warp moves the point at which the diagram is read,
     * not the sites, so the network stays connected.
     */
    public double fieldWarpAmplitude = 220;
    public double fieldWarpWavelength = 700;
    /**
     * Constant shift added to the warp, blocks. It has no visual purpose; it keeps every seed's
     * ridges where they were before the warp formula was corrected (Nov 2026). Setting it to 0
     * moves the whole ridge network diagonally by about 190 blocks.
     */
    public double fieldWarpShift = -137.5;
    /**
     * Field layout mask: a cell is in the mountains when vanilla's footprint is on at its site, so
     * the mountain edge follows whole cells and the last ridge stands at full height; the mask
     * then runs one flank beyond the last ridge and fades over this many blocks into vanilla.
     * Wider = a gentler hand-over to vanilla terrain, but more of our flank shows past the
     * footprint.
     */
    public double fieldEdgeFade = 120;
    /**
     * How far below the valley floor our surface sinks where the mask is 0 (see
     * RegionCache.maskedHeight). In the fade band our surface therefore drops under vanilla's and
     * vanilla takes over by height, instead of our flat valley floor ending in a vertical face
     * wherever vanilla is lower (every shoreline was a 4-block step before this).
     */
    public double maskSink = 24;
    /**
     * Typical summit relief multiplier in the field layout (1.0 = the design summit). The relief is
     * fieldHeightBoost * (1 + fieldHeightVariation * n), n in -1..1 over fieldHeightWavelength
     * blocks: with 0.88 and 0.5 that is 0.44..1.32, mostly near 0.88. These are the values tuned
     * in game, restated after a range bug in the old formula was corrected (Nov 2026).
     */
    public double fieldHeightBoost = 0.88;
    /** Relief varies by this fraction either side of fieldHeightBoost ("some big, some small"). */
    public double fieldHeightVariation = 0.5;
    /**
     * Wavelength of the height-scale noise, blocks. Long enough that a whole massif shares one
     * scale, so big and small mountains come in groups rather than alternating peak by peak.
     */
    public double fieldHeightWavelength = 1800;

    // ---- Heightmap sampling ----------------------------------------------------------
    /**
     * Blocks per heightmap sample. Erosion runs on this grid and RegionCache interpolates between
     * samples (bicubic) plus a fine noise to hide the grid. 4 is the coarsest spacing at which the
     * gullies still read; 2 would quadruple erosion time.
     */
    public int sampleSpacing = 4;
    /**
     * Extra samples generated on every side of a region. Erosion near a region's edge needs the
     * terrain beyond it, and RegionCache cross-fades neighbouring regions over this overlap, so
     * the two erosion results meet without a seam. 64 samples = 256 blocks.
     */
    public int overlapSamples = 64;

    // ---- Vertical layout ---------------------------------------------------------
    /** Flat valley floor height (y). Lakes sit a few blocks below this after valley fill. */
    public double valleyFloorHeight = 64;   // one above vanilla sea level, so lakes share it
    /**
     * Design summit height (y), before the field layout's height scale. Relief = summitHeight -
     * valleyFloorHeight = 168 blocks; with the typical scale of 0.88 a summit stands at about
     * y 212, the tallest at about y 286. This is the "a decent bit smaller" size of 9 Nov 2026.
     */
    public double summitHeight = 232;
    /**
     * Fraction of the relief, measured down from the mean summit, that is rock face at the face
     * angle. Below that (the rock line, y 148 with the values above) the flank turns concave and
     * grassy. The material rules use the same line, which is why it is repeated in the datapack.
     */
    public double rockFraction = 0.5;

    // ---- Crest profile along a ridge ----------------------------------
    /**
     * Mean distance between summits along a crest. Each ridge is a row of peaks joined by saddles,
     * like the reference image (a ridge wall with pointed summits along it), not one long flat
     * crest and not isolated cones.
     */
    public double peakSpacing = 72;
    /** Peak position jitter as a fraction of peakSpacing, so the row of summits is not evenly spaced. */
    public double peakSpacingJitter = 0.25;
    /**
     * Extra height of the summit where ridges meet (a junction of the field layout), as a fraction
     * of the relief above the design summit. Without it a junction is wherever the ridges' own
     * summit rows happen to cross, usually a saddle, so the meeting of three ranges reads as a
     * flattened corner rather than the peak it should be. 0.15 makes it about 25 blocks taller than
     * a normal summit (before the height scale). Its faces fall away along each ridge at
     * crestFallSlope, like any other summit.
     */
    public double junctionPeakBoost = 0.15;
    /** Summit-to-summit height variation along a crest, as a fraction either side of the mean. */
    public double peakHeightVariation = 0.075;
    /**
     * Slope at which the ridge falls away from a summit along the crest (tan). 0.75 is 37 degrees
     * (0.6, 31 degrees, until Nov 2026; Sammi wanted sharper, more separate peaks, like the reference).
     * The true slope of a facet is sqrt(faceSlope^2 + crestFallSlope^2): 1.35 and 0.75 give 57 degrees.
     * This is what makes each summit a pointed pyramid rather than a bump on a level wall.
     */
    public double crestFallSlope = 0.75;
    /** Rounding of the saddle between two summits, blocks. 0 is a sharp V. Summits are never rounded. Was 12 until Nov 2026. */
    public double saddleRounding = 6;
    /**
     * Summits closer together than this keep a sharp V saddle (Sammi chose rounded saddles that stay
     * sharp between close peaks). Between this and saddleRoundingMaxGap the rounding ramps up.
     */
    public double saddleRoundingMinGap = 64;
    /** Summits further apart than this get the full saddleRounding. */
    public double saddleRoundingMaxGap = 112;

    // ---- Legs (side ridges) ---------------------------------------------
    /*
     * Side ridges branching off the summits at an angle and running down the faces and flanks
     * (Nov 2026: Sammi wanted arms like those inside an area on the big plain outer walls too).
     * See HeightmapGenerator.spurHeight.
     */
    /** Share of summits with a leg on each side (0 turns legs off). */
    public double spurChance = 0.4;
    /** Angle of a leg off straight down the face, degrees, chosen per summit in this range. */
    public double spurAngleMin = 15;
    public double spurAngleMax = 50;
    /** Slope of a leg's crest as it runs out from the summit (tan). 0.5 is 27 degrees. */
    public double spurFallSlope = 0.5;
    /** Slope of a leg's sides (tan). 1.1 is 48 degrees: a sharp arete. */
    public double spurSideSlope = 1.1;
    /** Spacing of the little peaks along a leg, blocks (each leg varies it by +/- 20%). */
    public double spurPeakSpacing = 60;
    /** Depth of the notches between those peaks, blocks. */
    public double spurNotchDepth = 14;
    /** Legs fade out between these distances from their ridge, in half-widths. */
    public double spurFadeStart = 0.8;
    public double spurReach = 1.3;
    /** A leg fades out over this many blocks before its ridge stops being one of the two nearest. */
    public double spurHandover = 40;
    /** Sideways bend of a leg at its full reach, as a fraction of the reach (sign chosen per leg). */
    public double spurBend = 0.3;

    // ---- Cross profile --------------------------------------------------
    /**
     * Face slope on rock, as tan, measured straight down from the crest. 1.0 is 45 degrees, 1.35
     * is 53 degrees (1.15, 49 degrees, until Nov 2026: Sammi found that version too rounded). This
     * sets the angular look; much past ~55 degrees the faces read as vertical walls once voxelised,
     * gentler and the mountains read as hills. Steeper faces also shorten the rock run, so each
     * range is about 10 blocks narrower on each side than with 1.15.
     */
    public double faceSlope = 1.35;
    /**
     * Flank slope just below the rock line, as tan (0.9 is 42 degrees). The flank then eases out
     * to flat at the valley edge, following flankConcavity.
     */
    public double flankTopSlope = 0.90;
    /**
     * Concavity exponent of the grass flank. 1 is a straight slope from the rock line to the valley
     * floor; higher puts more of the drop near the top, so the foot of the flank runs out long and
     * gentle, like a scree apron. 1.3 until Nov 2026; Sammi wanted the foot to curve out into the
     * land more gradually.
     */
    public double flankConcavity = 1.7;

    // ---- Detail noise ---------------------------------------------------
    /**
     * Peak-to-trough amplitude of the ridged detail noise at the summits, blocks. Seasoning, not
     * shape: it breaks up the planar faces before erosion, so the droplets have something to follow.
     */
    public double detailAmplitude = 5.5;
    /** Wavelength of the largest detail octave, blocks. */
    public double detailWavelength = 44;
    /** Octaves of ridged noise; each halves the wavelength and the amplitude. */
    public int detailOctaves = 3;
    /**
     * Detail amplitude is scaled by ((h - floor) / relief) ^ this, so the detail is strongest on the
     * upper faces and the flanks and valley floors stay smooth.
     */
    public double detailHeightPower = 2.0;

    // ---- Valley floor and lakes --------------------------------------------------
    /** Lake bed depth below the valley floor at the deepest point, blocks. */
    public double lakeDepth = 5;
    /** Fraction of the floor width taken by the lake where there is one. */
    public double lakeWidthFraction = 0.5;
    /** Wavelength along the valley of the on/off pattern of lakes, blocks. */
    public double lakeWavelength = 720;
    /** Roughly the fraction of valley length that has a lake (0 none, 1 continuous). */
    public double lakeCoverage = 0.55;

    // ---- Thermal erosion ------------------------------------------------
    /*
     * Thermal erosion moves material from any sample that is steeper than a critical angle
     * relative to a neighbour down to that neighbour, a fraction of the excess per pass. It is the
     * "scree" pass: it rounds off spikes left by the detail noise and keeps faces at a consistent
     * angle. See erosion/ThermalErosion.
     */
    /**
     * Critical angle on rock, degrees. Computed for a face slope of 1.25 and crest fall 0.75 (55
     * degrees), so it is a little below the facet slope actually built (57 degrees) and thermal
     * erosion still trims the faces slightly. Until Nov 2026 it was computed for 1.0 and 0.6 (49
     * degrees), which rounded every crest back down whatever faceSlope was.
     */
    public double thermalRockAngle = Math.toDegrees(Math.atan(Math.sqrt(1.25 * 1.25 + 0.75 * 0.75)));
    /** Critical angle below the rock line, degrees (gully walls on the grass flank). */
    public double thermalFlankAngle = 36;
    /** Height band over which the critical angle blends, blocks, centred on the rock line. */
    public double thermalBlendBand = 30;
    /** Fraction of the excess moved per neighbour per pass. Higher converges faster but can oscillate. */
    public double thermalRate = 0.25;
    /** Passes before hydraulic erosion. */
    public int thermalPassesBefore = 40;
    /** Passes after hydraulic erosion, to restore the face angle around gullies. */
    public int thermalPassesAfter = 40;

    // ---- Hydraulic erosion (Beyer droplets) ------------------------------
    /*
     * Hydraulic erosion simulates rain: each droplet starts at a random point, runs downhill with
     * some inertia, picks up sediment where it speeds up and drops it where it slows down. Tens of
     * thousands of droplets carve the branching gullies on the faces. The droplet constants follow
     * Hans Theobald Beyer's 2015 thesis "Implementation of a method for hydraulic erosion"; see
     * erosion/HydraulicErosion for what each one does.
     */
    /** Droplets per region. Doubling it roughly doubles erosion time and deepens the gullies. */
    public int dropletsPerRegion = 50_000;
    /** Droplets erode only above (rock line - this); below it they only deposit, so the grass flanks stay smooth. */
    public double hydraulicErodeBelowRockLine = 8;
    /** Width of the blend band under that height, blocks. */
    public double hydraulicErodeBand = 16;
    /** Most steps a droplet takes before it is dropped. */
    public int dropletMaxLifetime = 120;
    /** How much of its previous direction a droplet keeps each step (0 = follows the slope exactly). */
    public double dropletInertia = 0.1;
    /** Sediment capacity factor: capacity = slope * speed * water * this. */
    public double dropletCapacity = 2.5;
    /** Lowest slope used in the capacity formula, so droplets on flat ground still carry a little. */
    public double dropletMinSlopeCapacity = 0.01;
    /** Fraction of the surplus sediment dropped per step when over capacity. */
    public double dropletDeposit = 0.3;
    /** Fraction of the spare capacity taken from the ground per step when under capacity. */
    public double dropletErode = 0.3;
    /** Fraction of the droplet's water lost per step. */
    public double dropletEvaporate = 0.015;
    /** Acceleration from the height drop each step. */
    public double dropletGravity = 0.5;
    /** Speed cap so droplets on long faces do not run away. */
    public double dropletMaxSpeed = 3;
    /** Most height a droplet may remove from its footprint in one step, blocks. */
    public double dropletMaxErodePerStep = 0.3;
    public double dropletInitialSpeed = 1;
    public double dropletInitialWater = 1;
    /** Erosion brush radius in samples: the droplet takes material from this neighbourhood, not one sample. */
    public int dropletRadius = 1;

    // ---- Vanilla's mountain footprint (mixed preset) -----------------------------------------
    /*
     * In the mixed preset our mountains replace vanilla's: they appear where vanilla's own
     * mountain biomes would be. Vanilla puts its peaks where its erosion noise is very low, so a
     * cell of our field layout is "mountain" when that noise, read at the cell's site, is below a
     * threshold. Deciding per cell rather than per block means the edge follows whole ridges and
     * the last ridge stands at full height (scaled-down "long low" edge ridges were rejected).
     */
    /**
     * A field cell is mountain when the world's erosion at its site, plus the ragged noise below,
     * is under this. Lower = fewer, smaller provinces. Set so our mountains cover about the same
     * share of land as vanilla's own mountain biomes (Sammi: replace vanilla's mountains 1:1, as
     * common as any other biome), then each area made 20% wider at his request with the number of
     * areas kept. Measured with /atlasmountains footprint and biomes (Nov 2026): vanilla's peaks,
     * slopes, groves, meadows and windswept hills take about 5.6% of land; -0.62 with
     * footprintErosionScale 2.08 gives about 9 to 10% (-0.72 with 2.5 gave 5 to 8%, and -0.32 with
     * 2.5, the value before that, about 40%).
     */
    public double erosionMountainBelow = -0.46;   // -0.62 with the cell-edge layout; the ridge skeleton covers less ground per cell, so the threshold was raised to keep about 7% of land
    /**
     * Province edges are roughened: a cell counts as mountain when erosion + footprintRagged * n
     * (n in -1..1, wavelength footprintRaggedWavelength) is below the threshold, so the edge breaks
     * into bays and outliers instead of following one smooth erosion contour (the "goofy" smooth
     * arc on the map).
     */
    public double footprintRagged = 0.2;
    /**
     * The footprint reads the erosion noise at this many times the biome layer's frequency, so
     * mountain provinces are smaller than the other biomes (2 = vanilla-sized provinces while the
     * biomes stay at twice vanilla). 2.08 is 2.5 / 1.2: provinces 20% wider than at 2.5.
     */
    public double footprintErosionScale = 2.08;
    /** Wavelength of the ragged-edge noise, blocks. */
    public double footprintRaggedWavelength = 900;
    /**
     * The erosion noise is stretched by this ratio along a seed-chosen direction (1 = no stretch;
     * 2, elongated provinces, was tried and dropped).
     */
    public double erosionStretch = 1.0;

    // ---- Coast fade of the mountains ------------------------------------------------
    /*
     * Mountains fade out towards the sea, so a range never ends in a sheer sea cliff. The fade is
     * on continentalness (vanilla's land-versus-sea value, here produced by NoiseContinents).
     */
    /** Continentalness at and below which mountains are fully faded out (coast is -0.19..-0.11; -0.15 is the shoreline). */
    public double maskInlandStart = -0.15;
    /** Continentalness at and above which mountains are fully on. */
    public double maskInlandFull = 0.05;

    // ---- Continents (mixed preset; NoiseContinents replaces vanilla continentalness) ----
    /** Wavelength of the largest continent noise octave, blocks. Sets continent and ocean size. */
    public double continentWavelength = 36000;
    /** Octaves of continent noise; each halves the wavelength. More = finer coastal detail. */
    public int continentOctaves = 7;
    /** Amplitude falloff per octave (0.5 = rough coasts, 0.65 = rougher, 0.4 = smooth blobs). */
    public double continentGain = 0.5;
    /** Noise value above which there is land. Higher = less land. About 0.1 gives a third land. */
    public double continentLandThreshold = 0.18;
    /** Spawn island: the noise is raised by this at the origin, fading out over continentSpawnRadius blocks. */
    public double continentSpawnBoost = 0.4;
    public double continentSpawnRadius = 12000;
    /** Land is guaranteed within this radius of the origin (a dome of at least this noise value above the threshold at the centre). */
    public double continentSpawnGuaranteedRadius = 5000;
    public double continentSpawnGuaranteedValue = 0.25;

    // ---- Continentalness ramp: signed distance to the shore -> vanilla's scale (Continents.fromDistance)
    /*
     * Vanilla's biome and terrain code expects continentalness on its own scale (about -1 deep
     * ocean, -0.19..-0.11 coast, 0.3 and up far inland). NoiseContinents produces a distance to the
     * shoreline instead, and these distances map it onto that scale piece by piece, so beaches,
     * oceans and inland biomes keep vanilla's widths.
     */
    /** Half-width of the coast band, blocks: continentalness runs -0.25..-0.05 over +/- this around the shoreline. */
    public double coastHalfWidth = 100;
    /** Blocks inland at which continentalness reaches 0.05 (near inland ends, mountains fully on). */
    public double nearInlandDistance = 250;
    /** Blocks inland at which continentalness reaches 0.45 (far inland). */
    public double farInlandDistance = 1200;
    /** Blocks offshore at which continentalness reaches -0.5 (ocean). */
    public double oceanDistance = 700;
    /** Blocks offshore at which continentalness reaches -1.0 (deep ocean). */
    public double deepOceanDistance = 3000;

    // ---- Derived helpers ---------------------------------------------------------
    /*
     * Lengths that follow from the settings above. They are methods, not fields, so they can never
     * fall out of step with the values they come from.
     */
    /** Height of the design summit above the valley floor, blocks (168 with the shipped values). */
    public double relief() { return summitHeight - valleyFloorHeight; }
    /** Height (y) where the rock face ends and the grass flank begins (148 with the shipped values). */
    public double rockLineHeight() { return summitHeight - rockFraction * relief(); }
    /** Height of the grass flank, from the valley floor up to the rock line. */
    public double flankRelief() { return rockLineHeight() - valleyFloorHeight; }
    /** Horizontal length of the flank from rock line to valley edge, for the mean crest height. */
    public double flankLength() { return flankConcavity * flankRelief() / flankTopSlope; }
    /** Horizontal run of the rock face from the mean summit down to the rock line. */
    public double meanRockRun() { return (summitHeight - rockLineHeight()) / faceSlope; }
    /** Distance from a ridge line to the valley edge; a range's half-width. */
    public double halfWidth() { return meanRockRun() + flankLength(); }
    /** Heightmap samples along one side of a region, without the overlap. */
    public int samplesPerRegion() { return regionSizeBlocks / sampleSpacing; }
    /** Heightmap samples along one side of a region's grid, including the overlap on both sides. */
    public int gridSize() { return samplesPerRegion() + 2 * overlapSamples; }
}
